"""Build a strict-grounding SFT dataset from the med-rag-vertex synthetic corpus.

WHY THIS EXISTS
---------------
The med-rag-vertex evaluation, once its judge was actually shown the retrieved
documents, failed 4 of 24 cases — every failure the same shape: the answer
asserted a clinically specific claim the retrieved sources did not contain.
A fabricated BI-RADS 4C statistic. A quoted "Teaching point" present in no
source. An unsupported note on variants of uncertain significance. A pCR
definition presented as evidence-backed.

That is a behavioural failure, not a retrieval failure — retrieval had already
put the right document in front of the model (gold retrieved 23/24). So this
dataset trains one behaviour: answer strictly from the provided context, and
say plainly when the context does not support something.

WHAT IT GENERATES
-----------------
Three example types, deliberately mixed:

  grounded   — the context contains the answer. Answer it, citing the source
               file it came from.
  abstain    — the question is clinically reasonable but the context does NOT
               contain the answer. The model must say so instead of filling
               the gap from parametric memory. This is the type that fixes the
               observed failures.
  partial    — the context answers part of the question. Answer that part,
               and name what is missing.

Examples are generated by Gemini from the corpus, then MECHANICALLY VERIFIED:
any "grounded" answer containing a quoted span not present in its context is
dropped rather than trusted. The generator is not the judge of its own output.

    python build_dataset.py            # writes data/train.jsonl, data/eval_held_out.jsonl
"""

from __future__ import annotations

import argparse
import json
import os
import random
import re
import sys
from pathlib import Path

from dotenv import load_dotenv
from google import genai
from google.genai import types

ROOT = Path(__file__).resolve().parent
CORPUS = ROOT.parent / "med-rag-vertex"
DATA = ROOT / "data"
GEN_MODEL = "gemini-2.5-flash"

# The system prompt the tuned model is trained to obey. Kept identical at
# training and evaluation time — a tune that only works under a different
# prompt than it will be served with is not a real improvement.
SYSTEM = """You are a clinical decision-support assistant. You answer ONLY from the
CONTEXT provided in the user message.

Rules, in priority order:
1. Every clinical claim you make must be supported by the CONTEXT. Cite the source
   filename in brackets, e.g. [2025-03-14_case_early_lump_62F.md].
2. If the CONTEXT does not support an answer, say so explicitly and state what
   information would be needed. Do not fill the gap from general knowledge.
3. If the CONTEXT answers only part of the question, answer that part and name
   what is missing.
4. Never invent statistics, quotations, or study findings. If you did not read it
   in the CONTEXT, you do not have it.
5. This is decision support. The clinician decides."""


def load_corpus() -> list[tuple[str, str]]:
    docs = []
    for sub in ("docs_cases", "docs_guides"):
        d = CORPUS / sub
        if not d.exists():
            sys.exit(f"corpus not found: {d}\nRun this from a checkout next to med-rag-vertex/")
        for f in sorted(d.glob("*.md")):
            docs.append((f.name, f.read_text(encoding="utf-8")))
    return docs


GEN_PROMPT = """You are building training data that teaches a clinical assistant to answer
STRICTLY from provided context and to refuse when the context is insufficient.

Below are {n} documents from a synthetic breast-cancer reference corpus.

{corpus}

Produce exactly {k} training examples as a JSON array. Each element:
{{
  "type": "grounded" | "abstain" | "partial",
  "context_files": ["<filename>", ...],   // 1-3 files, must be from the list above
  "question": "<a clinician's question, Korean or English>",
  "answer": "<the ideal answer under the rules below>"
}}

Distribution: about {n_ground} "grounded", {n_abstain} "abstain", {n_partial} "partial".

Rules for the "answer" field — this is the behaviour being taught:
- grounded: fully answerable from the named context files. Answer it and cite the
  filename in brackets. Use ONLY facts that appear in those files.
- abstain: the question is clinically sensible but the named context files do NOT
  contain the answer. The answer must say plainly that the provided sources do not
  cover it, and state what would be needed. It must NOT answer from general medical
  knowledge, however confident. Choose questions that a model would be tempted to
  answer from memory — specific statistics, guideline thresholds, drug dosing,
  survival rates.
- partial: the context answers part. Answer that part with a citation, then name
  precisely what is not in the sources.

Write questions the way clinicians actually ask — terse, mixed Korean/English medical
terminology. Vary length. Do not make every answer the same shape.

Return ONLY the JSON array."""


def verify(ex: dict, corpus: dict[str, str]) -> tuple[bool, str]:
    """Mechanical checks. The generator does not get to grade itself."""
    if ex.get("type") not in {"grounded", "abstain", "partial"}:
        return False, "bad type"
    files = ex.get("context_files") or []
    if not files or not all(f in corpus for f in files):
        return False, "unknown context file"
    q, a = ex.get("question", ""), ex.get("answer", "")
    if len(q) < 8 or len(a) < 20:
        return False, "too short"

    ctx = "\n".join(corpus[f] for f in files)

    # A grounded/partial answer that quotes something must actually quote the
    # context. This is exactly the failure mode observed in the eval (a quoted
    # "Teaching point" that existed in no source), so it is checked, not assumed.
    for quoted in re.findall(r'"([^"]{12,})"', a):
        if quoted not in ctx:
            return False, f"quotes text absent from context: {quoted[:40]}"

    if ex["type"] == "abstain":
        # An abstention that does not signal insufficiency is not an abstention.
        signals = ["제공된", "자료에", "출처", "포함되어 있지", "없습니다", "not contain",
                   "do not contain", "does not", "not available", "insufficient",
                   "not covered", "확인할 수 없", "나와 있지"]
        if not any(s in a for s in signals):
            return False, "abstain example does not actually abstain"
    return True, "ok"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--batches", type=int, default=8, help="generation batches")
    ap.add_argument("--per-batch", type=int, default=12)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    load_dotenv(CORPUS / ".env")
    if not os.environ.get("GOOGLE_CLOUD_PROJECT"):
        sys.exit("GOOGLE_CLOUD_PROJECT not set (expected in med-rag-vertex/.env)")

    random.seed(args.seed)
    docs = load_corpus()
    corpus = dict(docs)
    print(f"corpus: {len(docs)} documents")

    client = genai.Client()
    seen: set[str] = set()
    kept: list[dict] = []
    rejected: dict[str, int] = {}

    for b in range(args.batches):
        # Rotate a document window per batch so questions spread across the corpus.
        window = random.sample(docs, k=min(8, len(docs)))
        blob = "\n\n".join(f"### {name}\n{text[:1800]}" for name, text in window)
        k = args.per_batch
        prompt = GEN_PROMPT.format(
            n=len(window), corpus=blob, k=k,
            n_ground=k // 2, n_abstain=k // 3, n_partial=k - k // 2 - k // 3,
        )
        try:
            resp = client.models.generate_content(
                model=GEN_MODEL, contents=prompt,
                config=types.GenerateContentConfig(response_mime_type="application/json"),
            )
            items = json.loads(resp.text)
        except Exception as e:
            print(f"  batch {b + 1}: generation failed ({type(e).__name__}), skipping")
            continue

        added = 0
        for ex in items if isinstance(items, list) else []:
            ok, why = verify(ex, corpus)
            if not ok:
                rejected[why.split(":")[0]] = rejected.get(why.split(":")[0], 0) + 1
                continue
            key = ex["question"].strip()[:80]
            if key in seen:
                rejected["duplicate"] = rejected.get("duplicate", 0) + 1
                continue
            seen.add(key)
            kept.append(ex)
            added += 1
        print(f"  batch {b + 1}/{args.batches}: +{added} kept (total {len(kept)})")

    if len(kept) < 20:
        sys.exit(f"only {len(kept)} usable examples — not enough to train on")

    # Format for SFT. Context is rendered exactly as it will be at serving time.
    def to_chat(ex: dict) -> dict:
        ctx = "\n\n".join(f"--- {f} ---\n{corpus[f]}" for f in ex["context_files"])
        return {
            "type": ex["type"],
            "messages": [
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": f"CONTEXT:\n{ctx}\n\nQUESTION: {ex['question']}"},
                {"role": "assistant", "content": ex["answer"]},
            ],
        }

    random.shuffle(kept)
    n_hold = max(12, len(kept) // 6)
    held, train = kept[:n_hold], kept[n_hold:]

    DATA.mkdir(exist_ok=True)
    for name, rows in (("train.jsonl", train), ("eval_held_out.jsonl", held)):
        with open(DATA / name, "w", encoding="utf-8") as f:
            for ex in rows:
                f.write(json.dumps(to_chat(ex), ensure_ascii=False) + "\n")

    def dist(rows):
        d: dict[str, int] = {}
        for r in rows:
            d[r["type"]] = d.get(r["type"], 0) + 1
        return d

    print(f"\ntrain: {len(train)} {dist(train)}")
    print(f"held out: {len(held)} {dist(held)}")
    print(f"rejected by verification: {rejected}")
    print(f"→ {DATA}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
